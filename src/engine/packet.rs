use bytes::Bytes;

/// Maximum RTP packet size for SMPTE 2022-2 (7 x 188 byte TS packets + 12 byte RTP header)
pub const MAX_RTP_PACKET_SIZE: usize = 1500;

/// Broadcast channel capacity for fan-out — the `Standard` tier of
/// [`crate::config::models::BandwidthProfile`].
///
/// Sized for TS-class contribution / distribution flows (up to ~500 Mbps
/// compressed video). At 1316 bytes per RTP packet (7×188 TS + 12 RTP
/// header), 16 384 slots ≈ 21 MB buffer providing ~3.4 seconds at
/// 50 Mbps, ~344 ms at 500 Mbps, or ~56 ms at 3 Gbps. Slow subscribers
/// receive `RecvError::Lagged` and drop — the input is never blocked.
///
/// **Per-flow override**: when [`crate::config::models::FlowConfig::bandwidth_profile`]
/// is set (or auto-derived to `HighBitrate` / `Uncompressed`) the
/// runtime uses [`crate::config::models::BandwidthProfile::broadcast_capacity`]
/// instead of this constant — see
/// [`crate::engine::bandwidth_profile::resolve_for_flow`]. This constant
/// remains the fallback for code paths that don't have a flow context
/// (tests, isolated channel construction).
#[allow(dead_code)]
pub const BROADCAST_CHANNEL_CAPACITY: usize = 16_384;

/// The packet that flows through broadcast channels.
///
/// Carries either:
/// - **RTP-wrapped TS** (SMPTE ST 2022-2): `data` includes the 12+ byte RTP header
///   followed by MPEG-2 TS packets. `sequence_number` and `rtp_timestamp` are parsed
///   from the RTP header.
/// - **Raw TS** (e.g. from OBS, Haivision, srt-live-transmit): `data` contains raw
///   188-byte MPEG-2 TS packets with no RTP header. `sequence_number` is synthetically
///   generated by the input for stats/ordering. `is_raw_ts` is set to true.
///
/// Outputs must check `is_raw_ts` to determine whether to strip an RTP header or
/// forward the data as-is.
#[derive(Clone, Debug)]
pub struct RtpPacket {
    /// Raw packet data — either RTP header + TS payload, or raw TS bytes.
    pub data: Bytes,
    /// RTP sequence number (from header if RTP, synthetic if raw TS).
    pub sequence_number: u16,
    /// RTP timestamp (from header if RTP, synthetic from wall clock if raw TS).
    pub rtp_timestamp: u32,
    /// Monotonic receive time in microseconds (for stats/throughput).
    pub recv_time_us: u64,
    /// True when the data is raw TS (no RTP header). Outputs that strip RTP
    /// headers should skip stripping when this is set.
    pub is_raw_ts: bool,
    /// Upstream wire sequence number when known, so the pre-bus seq-aware
    /// hitless merger (`engine::ts_es_hitless`) can dedup + gap-fill against
    /// the authoritative wire-level seq instead of relying on a 200 ms stall
    /// timer; the PID bus carries it onto each TS packet of the datagram
    /// with that packet's place in it. Whether a packet has it is the
    /// runtime's rule, not its input type: only `input_rtp` (a FEC-decoded one too) and `input_rist` stamp it, and a packet through an ingress transcode or post-process stage (`audio_encode` / `video_encode`, `program_number`, `pid_overrides`, `pid_map`, or the muxer-mode clock regenerator that runs on an input of a flow with no `assembly` unless `passthrough_clock: true`) leaves without it (`process_input_packet_with_post`) — what
    /// `config::validation::upstream_seq_missing` asks of a seq-aware
    /// Hitless leg. `None` from SRT, UDP and every other input.
    pub upstream_seq: Option<u16>,
    /// 2022-7 leg identity (0 = primary, 1 = backup). `None` for
    /// single-leg inputs. Used by the seq-aware merger to attribute
    /// failover events.
    pub upstream_leg_id: Option<u8>,
    /// Sender-set per-packet timestamp in microseconds since the Unix
    /// epoch, when the transport surfaces it. Today: libsrt's
    /// `SRT_MsgCtrl::srctime` reaches us as `Some(_)` on raw-TS-over-
    /// SRT inputs; everywhere else this is `None`. Consumed by
    /// `engine::master_clock::SenderTimestampMaster` for PLL rate
    /// recovery on internet-contribution paths where MPEG-TS PCR
    /// sampled from the bytes after a 200 ms+ latency-buffer release
    /// is too bursty for the PLL to lock cleanly. Sender timestamps
    /// are set at `sendmsg()` time — pre-network-jitter — so they
    /// are not affected by TSBPD release cadence at the receiver.
    pub sender_timestamp_us: Option<i64>,
}

/// TS packets per broadcast item for a source that muxes its own transport
/// stream: 7 × 188 = 1316 bytes, the payload every datagram output sends (SRT
/// live mode, UDP, RTP) and what the media player, the multiviewer and the
/// test pattern already publish.
pub const TS_PACKETS_PER_ITEM: usize = 7;

/// Group the 188-byte TS packets one mux call produced into broadcast items of
/// up to [`TS_PACKETS_PER_ITEM`] packets, in order.
///
/// A source that published each packet as its own item (SDI did, until
/// edge#166) left the edge as one datagram per TS packet: 5,800 datagrams a
/// second of 204 bytes for an 8.5 Mbit/s SRT feed instead of ~830 of 1332,
/// 23 % wire overhead, and every buffer sized in packets — libsrt's, the
/// flow's broadcast ring, quinn's datagram queue — seven times shallower in
/// time than its number reads. SRT's output splits large items but never joins
/// small ones, so it has to happen here.
///
/// Only the packets of one call are grouped — a call is one access unit, one
/// audio frame or one section — so nothing waits for the next call. A batch
/// of one is passed on as it is, without a copy.
pub fn bundle_ts_packets(packets: Vec<Bytes>) -> Vec<Bytes> {
    if packets.len() <= 1 {
        return packets;
    }
    packets
        .chunks(TS_PACKETS_PER_ITEM)
        .map(|group| {
            if group.len() == 1 {
                return group[0].clone();
            }
            let mut item = bytes::BytesMut::with_capacity(group.iter().map(Bytes::len).sum());
            for p in group {
                item.extend_from_slice(p);
            }
            item.freeze()
        })
        .collect()
}

#[cfg(test)]
mod bundle_tests {
    use super::*;

    fn ts(n: u8) -> Bytes {
        let mut p = vec![n; 188];
        p[0] = 0x47;
        Bytes::from(p)
    }

    #[test]
    fn packets_are_grouped_seven_to_an_item_in_order() {
        let packets: Vec<Bytes> = (0..16).map(ts).collect();
        let items = bundle_ts_packets(packets.clone());
        assert_eq!(items.iter().map(Bytes::len).collect::<Vec<_>>(), [1316, 1316, 376]);
        let flat: Vec<u8> = items.iter().flat_map(|b| b.iter().copied()).collect();
        let want: Vec<u8> = packets.iter().flat_map(|b| b.iter().copied()).collect();
        assert_eq!(flat, want, "bytes and order unchanged");
    }

    #[test]
    fn small_batches_pass_through() {
        assert!(bundle_ts_packets(Vec::new()).is_empty());
        let one = ts(1);
        let items = bundle_ts_packets(vec![one.clone()]);
        assert_eq!(items, std::slice::from_ref(&one));
        assert_eq!(items[0].as_ptr(), one.as_ptr(), "a lone packet is not copied");
        let seven: Vec<Bytes> = (0..7).map(ts).collect();
        assert_eq!(bundle_ts_packets(seven).len(), 1);
        let eight: Vec<Bytes> = (0..8).map(ts).collect();
        let items = bundle_ts_packets(eight);
        assert_eq!(items.iter().map(Bytes::len).collect::<Vec<_>>(), [1316, 188]);
    }
}
